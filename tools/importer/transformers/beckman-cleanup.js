/**
 * Beckman (mybeckman.in) cleanup transformer.
 * Removes non-authorable site chrome and empty spacer containers.
 * Also removes the source breadcrumbs (the site builds them from the page path).
 * Keeps the h1 + .softwareContainer.
 */
export default function transform(hookName, element, payload) {
  if (hookName === 'beforeTransform') {
    // Overlays / widgets that could interfere with block matching
    WebImporter.DOMUtils.remove(element, [
      '#consent_blackbar', // cookie consent banner
      '#ModalPopup.access-restriced-login-modal', // empty login modal
      '#ModalPopup',
      '.MaskOverlay',
    ]);

    // Breadcrumbs are generated by the site from the page path, not authored.
    // Their labels (below Home) are kept for the "Breadcrumb Labels" page metadata.
    const crumbs = [...element.querySelectorAll('nav.breadcrumbs li')]
      .map((li) => li.textContent.replace(/\s+/g, ' ').trim())
      .filter(Boolean)
      .slice(1);
    if (crumbs.length) {
      element.ownerDocument.documentElement.dataset.breadcrumbLabels = crumbs.join(' | ');
    }
    WebImporter.DOMUtils.remove(element, [
      '#main .main-holder > .container.custome-container',
      'nav.breadcrumbs',
    ]);

    // Empty spacer containers inside the main content area
    element.querySelectorAll('.product-series-callouts').forEach((band) => {
      if (!band.querySelector('.product-series-callouts__item')) band.remove();
    });
    WebImporter.DOMUtils.remove(element, [
      '.series-category-promotional-wrapper',
      '#main .main-holder > .row.js-component',
      '.two-columns-holder .row.js-component',
      '.bcls-aeo-published',
    ]);

    // Rich text sometimes leaves the real link empty and puts its text in the name
    // anchor right after it: move that text into the link.
    element.querySelectorAll('#main a[href]').forEach((a) => {
      if (a.textContent.trim()) return;
      const next = a.nextElementSibling;
      if (next && next.tagName === 'A' && !next.hasAttribute('href') && next.textContent.trim()) {
        a.replaceChildren(...next.childNodes);
        next.remove();
      }
    });

    // The importer may already have dropped the empty link; recover its target from
    // the raw source (<a href="X"><span></span></a><a>Text</a>).
    const raw = (payload && payload.html) || '';
    const recovered = {};
    raw.replace(/<a href="([^"]+)">(?:\s*<span[^>]*>\s*<\/span>\s*)?<\/a>\s*<a>([^<]+)<\/a>/g, (m, href, text) => {
      recovered[text.trim()] = href;
      return m;
    });
    element.querySelectorAll('#main a:not([href])').forEach((a) => {
      const href = recovered[a.textContent.trim()];
      if (href) a.setAttribute('href', href);
    });

    // Name anchors (<a> without href) carry no content
    element.querySelectorAll('#main a:not([href])').forEach((a) => {
      if (!a.textContent.trim() && !a.querySelector('img')) a.remove();
      else a.replaceWith(...a.childNodes);
    });

    // Images wrapped in dead "#" links are plain images
    element.querySelectorAll('#main a[href="#"]').forEach((a) => {
      if (a.querySelector('img')) a.replaceWith(...a.childNodes);
    });

    // Rich text indents a sub-list with a separate, margin-shifted <ul>:
    // nest it under the previous list's last item and merge the list that follows.
    element.querySelectorAll('#main .bc-rich-text > ul[style*="margin-left"]').forEach((sub) => {
      const prev = sub.previousElementSibling;
      if (!prev || prev.tagName !== 'UL' || !prev.lastElementChild) return;
      const next = sub.nextElementSibling;
      sub.removeAttribute('style');
      prev.lastElementChild.append(sub);
      if (next && next.tagName === 'UL' && !next.getAttribute('style')?.includes('margin-left')) {
        while (next.firstElementChild) prev.append(next.firstElementChild);
        next.remove();
      }
    });
  }

  if (hookName === 'afterTransform') {
    // Global header / navigation and global footer (incl. Marketo newsletter form)
    WebImporter.DOMUtils.remove(element, [
      'header#mainNav',
      '#mainNav',
      'header',
      'div.footer2023',
      '#navScrollContainer',
    ]);

    // Misc non-authorable leftovers
    WebImporter.DOMUtils.remove(element, [
      'a.skip-to-main-content-link',
      'input#userId',
      'input#contextItemId',
      '#mktoStyleLoaded',
      'form.mktoForm',
      'iframe',
      'script',
      'style',
      'noscript',
      'link',
      'img[width="1"][height="1"]', // tracking pixels
    ]);

    // Strip tracking / event attributes
    element.querySelectorAll('*').forEach((el) => {
      [...el.attributes].forEach(({ name }) => {
        if (/^on/i.test(name) || /^data-(track|gtm|analytics|ga)/i.test(name)) {
          el.removeAttribute(name);
        }
      });
    });
  }
}
